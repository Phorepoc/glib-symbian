#!/usr/bin/env python3
# gen_symtab.py <dll>.def <out>.sym -- the symbol table the GModule backend reads (overlay/phe_gmodule_symbian.c): "name ordinal" per line, from the DLL's own frozen .def
# ("name @ N NONAME [DATA]"). Install it as resource/gmodule/<dll name>.sym next to the DLL.
import re, sys
src, out = sys.argv[1:3]
lines = []
for l in open(src, newline="").read().replace("\r\n", "\n").splitlines():
    m = re.match(r"^\s*(\S+)\s*@\s*(\d+)", l)
    if m:
        lines.append("%s %s" % (m.group(1), m.group(2)))
open(out, "w", newline="\n").write("# symbol table of %s (generated by gen_symtab.py)\n" % src.replace("\\", "/").split("/")[-1] + "\n".join(lines) + "\n")
print(out, len(lines), "symbols")
